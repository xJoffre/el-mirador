create function order_line_price() returns trigger language plpgsql as $$
begin
  if tg_op = 'UPDATE' then
    new.unit_price := old.unit_price;
    new.currency := old.currency;
    return new;
  end if;
  if new.kind = 'product' then
    select price, currency into new.unit_price, new.currency from product_variant where id = new.product_variant_id;
  elsif new.kind = 'lunch_full' then
    select price_full, currency into new.unit_price, new.currency
    from daily_menu_dish where menu_date = new.menu_date and lunch_dish_id = new.main_dish_id;
  elsif new.kind = 'lunch_soup' then
    select price_alone, currency into new.unit_price, new.currency
    from daily_menu_dish where menu_date = new.menu_date and lunch_dish_id = new.soup_dish_id;
  else
    select price_alone, currency into new.unit_price, new.currency
    from daily_menu_dish where menu_date = new.menu_date and lunch_dish_id = new.main_dish_id;
  end if;
  if new.unit_price is null then
    raise exception 'order line % has no price', new.kind using errcode = 'check_violation';
  end if;
  return new;
end
$$;
comment on function order_line_price() is 'Copies the current price into a new order line and keeps it unchanged afterwards';
create trigger order_line_price before insert or update on order_line for each row execute function order_line_price();

create function order_total() returns trigger language plpgsql as $$
declare
  round_id bigint := case when tg_op = 'DELETE' then old.order_round_id else new.order_round_id end;
  order_id bigint;
begin
  select customer_order_id into order_id from order_round where id = round_id;
  update customer_order o set
    total = coalesce((select sum(l.unit_price * l.quantity) from order_line l join order_round r on r.id = l.order_round_id
      where r.customer_order_id = order_id), 0),
    currency = coalesce((select min(l.currency) from order_line l join order_round r on r.id = l.order_round_id
      where r.customer_order_id = order_id), o.currency)
  where o.id = order_id;
  return null;
end
$$;
comment on function order_total() is 'Recomputes the total of the order whose lines changed';
create trigger order_total after insert or update or delete on order_line for each row execute function order_total();

create function order_status() returns trigger language plpgsql as $$
declare
  current_status text;
  due numeric;
  paid numeric;
begin
  select status, total into current_status, due from customer_order where id = new.customer_order_id for update;
  if current_status <> 'open' then
    raise exception 'order % is already %', new.customer_order_id, current_status using errcode = 'check_violation';
  end if;
  if new.status = 'closed' then
    select coalesce(sum(amount), 0) into paid from payment where customer_order_id = new.customer_order_id;
    if paid < due then
      raise exception 'payments % do not cover the total %', paid, due using errcode = 'check_violation';
    end if;
  end if;
  update customer_order set status = new.status where id = new.customer_order_id;
  return new;
end
$$;
comment on function order_status() is 'Keeps the current status of the order, refuses changes to a closed or cancelled order and refuses to close it without full payment';
create trigger order_status after insert on order_status_change for each row execute function order_status();

