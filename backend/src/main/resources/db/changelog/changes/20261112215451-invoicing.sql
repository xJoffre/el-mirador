create table invoice_request (
  id bigint generated by default as identity primary key,
  customer_order_id bigint not null unique references customer_order on delete cascade,
  id_type text not null check (id_type in ('cedula', 'ruc', 'passport')),
  id_number text not null check (
    (id_type = 'cedula' and id_number ~ '^[0-9]{10}$')
    or (id_type = 'ruc' and id_number ~ '^[0-9]{13}$')
    or (id_type = 'passport' and id_number ~ '^[A-Z0-9]{5,20}$')
  ),
  name text not null check (btrim(name) <> ''),
  email text not null check (email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
  address text,
  status text not null default 'pending' check (status in ('pending', 'issued')),
  invoice_number text,
  verified_by bigint references staff_user,
  created_at timestamptz not null default now(),
  check ((status = 'issued') = (invoice_number is not null and verified_by is not null))
);
